"""Convert TTFs to M5GFX VLW font arrays. VLW: 6 BE int32 header, 7 BE int32 per glyph, 8-bit alpha bitmaps."""
import struct, sys, freetype

FONTS = [  # (symbol, ttf, pixel size, monochrome)
    ("FONT_HEAD48", "tools/fonts/Silkscreen-Regular.ttf", 48, True),
    ("FONT_HEAD32", "tools/fonts/Silkscreen-Regular.ttf", 32, True),
    ("FONT_BODY20", "tools/fonts/Inter.ttf", 20, False),
    ("FONT_MONO15", "tools/fonts/GeistMono.ttf", 15, False),
]

def glyph_bitmap(bm, mono):
    w, h, pitch, buf = bm.width, bm.rows, bm.pitch, bm.buffer
    out = bytearray()
    for y in range(h):
        row = buf[y * pitch:(y + 1) * pitch]
        if mono:
            for x in range(w):
                out.append(255 if (row[x >> 3] >> (7 - (x & 7))) & 1 else 0)
        else:
            out.extend(row[:w])
    return bytes(out)

def vlw(path, px, mono):
    face = freetype.Face(path)
    face.set_pixel_sizes(0, px)
    flags = freetype.FT_LOAD_RENDER | (freetype.FT_LOAD_TARGET_MONO if mono else 0)
    metas, bitmaps = [], []
    for cp in range(0x20, 0x7F):
        face.load_char(chr(cp), flags)
        g = face.glyph
        bm = glyph_bitmap(g.bitmap, mono)
        metas.append(struct.pack(">7i", cp, g.bitmap.rows, g.bitmap.width, g.advance.x >> 6, g.bitmap_top, g.bitmap_left, 0))
        bitmaps.append(bm)
    asc, desc = face.size.ascender >> 6, -(face.size.descender >> 6)
    header = struct.pack(">6i", len(metas), 11, px, 0, asc, desc)
    return header + b"".join(metas) + b"".join(bitmaps)

if __name__ == "__main__":
    with open(sys.argv[1], "w") as f:
        f.write("// Generated by tools/make_fonts.py. Fonts: Silkscreen, Inter, Geist Mono (SIL OFL 1.1, see tools/fonts).\n#pragma once\n#include <stdint.h>\n")
        for sym, path, px, mono in FONTS:
            data = vlw(path, px, mono)
            body = ",".join(str(b) for b in data)
            f.write(f"static const uint8_t {sym}[{len(data)}] = {{{body}}};\n")
