def cubics(d):
    nums = [float(x) for x in re.findall(r"-?\d+(?:\.\d+)?", d)]
    start, rest = (nums[0], nums[1]), nums[2:]
    segs, p = [], start
    for i in range(0, len(rest) - 5, 6):
        c1, c2, e = (rest[i], rest[i+1]), (rest[i+2], rest[i+3]), (rest[i+4], rest[i+5])
        segs.append((p, c1, c2, e)); p = e
    return segs

def bez(s, t):
    (x0, y0), (x1, y1), (x2, y2), (x3, y3) = s
    u = 1 - t
    return (u**3*x0 + 3*u*u*t*x1 + 3*u*t*t*x2 + t**3*x3, u**3*y0 + 3*u*u*t*y1 + 3*u*t*t*y2 + t**3*y3)

def resample(d, n, closed):
    dense = []
    for s in cubics(d):
        for k in range(200):
            dense.append(bez(s, k / 200))
    dense.append(bez(cubics(d)[-1], 1.0))
    lengths = [0.0]
    for a, b in zip(dense, dense[1:]):
        lengths.append(lengths[-1] + math.dist(a, b))
    total, out, j = lengths[-1], [], 0
    count = n if closed else n - 1
    for i in range(n):
        target = total * i / count
        while j < len(lengths) - 2 and lengths[j + 1] < target:
            j += 1
        seg = lengths[j + 1] - lengths[j] or 1
        t = (target - lengths[j]) / seg
        a, b = dense[j], dense[j + 1]
        out.append((a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t))
    return out

def emit(name, pts):
    body = ",\n".join(f"  {{{x:.2f}f, {y:.2f}f}}" for x, y in pts)
    return f"static const float {name}[{len(pts)}][2] = {{\n{body}\n}};\n"

